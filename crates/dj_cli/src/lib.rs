//! Pipeline driver: TypeScript source → IR (verified, optimized) →
//! bytecode (validated) → VM.

use std::fmt;

use dj_bytecode as bc;
use dj_ir as ir;
pub use dj_ir::passes::OptLevel;
use dj_vm::{Vm, VmOptions};

#[derive(Clone, Debug)]
pub struct CompileOptions {
    pub opt: OptLevel,
    pub debug_info: bool,
    pub embed_source: bool,
}

impl Default for CompileOptions {
    fn default() -> Self {
        CompileOptions { opt: OptLevel::Default, debug_info: true, embed_source: true }
    }
}

#[derive(Debug)]
pub enum CompileError {
    /// Source errors (parse, unsupported construct, semantic).
    Diagnostics { rendered: String, diagnostics: Vec<dj_frontend::Diagnostic> },
    /// Internal compiler error: the IR failed verification.
    Verify(String),
    /// Internal compiler error: generated bytecode failed validation.
    Validate(String),
}

impl fmt::Display for CompileError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CompileError::Diagnostics { rendered, .. } => f.write_str(rendered),
            CompileError::Verify(s) => write!(f, "internal error: IR verification failed:\n{s}"),
            CompileError::Validate(s) => write!(f, "internal error: bytecode validation failed:\n{s}"),
        }
    }
}

impl std::error::Error for CompileError {}

fn verify(m: &ir::Module, stage: &str) -> Result<(), CompileError> {
    ir::verify::verify_module(m).map_err(|errs| {
        let mut s = format!("after {stage}:\n");
        for e in errs {
            s.push_str(&format!("  {e:?}\n"));
        }
        CompileError::Verify(s)
    })
}

/// Frontend + verification + optimization.
pub fn compile_ir(source: &str, file: &str, opt: OptLevel) -> Result<ir::Module, CompileError> {
    let mut m = dj_frontend::compile_to_ir(source, file).map_err(|diagnostics| CompileError::Diagnostics {
        rendered: dj_frontend::render_diagnostics(&diagnostics, source, file),
        diagnostics,
    })?;
    verify(&m, "lowering")?;
    ir::passes::optimize(&mut m, opt);
    verify(&m, "optimization")?;
    Ok(m)
}

/// Full compilation to validated bytecode.
pub fn compile(source: &str, file: &str, opts: &CompileOptions) -> Result<bc::Module, CompileError> {
    let m = compile_ir(source, file, opts.opt)?;
    let b = dj_codegen::generate(&m, &dj_codegen::Options { debug_info: opts.debug_info, embed_source: opts.embed_source });
    bc::validate(&b).map_err(|errs| CompileError::Validate(errs.iter().map(|e| format!("  {e}\n")).collect()))?;
    Ok(b)
}

/// An uncaught exception, as text (VM values do not leave the VM thread).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RunError {
    /// `Name: message`.
    pub message: String,
    /// Stack trace when the thrown value was an Error.
    pub stack: Option<String>,
}

impl fmt::Display for RunError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "Uncaught {}", self.stack.as_deref().unwrap_or(&self.message))
    }
}

#[derive(Clone, Debug)]
pub struct RunResult {
    /// Captured console output (stdout and stderr interleaved).
    pub output: String,
    pub error: Option<RunError>,
    pub gc: dj_vm::GcStats,
}

/// Run a bytecode module to completion with captured output.
pub fn run_module(m: bc::Module, vm_opts: VmOptions) -> RunResult {
    let mut vm = Vm::new(VmOptions { capture_output: true, ..vm_opts });
    let error = match vm.load(m) {
        Ok(id) => vm.run_module(id).err().map(|u| RunError { message: u.message, stack: u.stack }),
        Err(e) => Some(RunError { message: e.to_string(), stack: None }),
    };
    RunResult { output: vm.take_output(), error, gc: vm.gc_stats() }
}

/// Compile and run with captured output.
pub fn run(source: &str, file: &str, opts: &CompileOptions, vm_opts: VmOptions) -> Result<RunResult, CompileError> {
    let m = compile(source, file, opts)?;
    Ok(run_module(m, vm_opts))
}

/// Run `f` on a thread with a large stack (deep native re-entry, recursive
/// formatting of deeply nested values).
pub fn run_on_big_stack<T: Send + 'static>(f: impl FnOnce() -> T + Send + 'static) -> T {
    std::thread::Builder::new()
        .name("djungle-vm".into())
        .stack_size(256 << 20)
        .spawn(f)
        .expect("spawn VM thread")
        .join()
        .unwrap_or_else(|p| std::panic::resume_unwind(p))
}
